"""Standalone offline verification suite for tslaiq-demo (reproducibility, OHLCV invariants, zero real data, zero secrets, JS syntax)."""

import csv
import datetime as dt
import hashlib
import json
import math
import re
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
CSV_PATH = ROOT / "data" / "synthetic_ohlcv.csv"
DATA_JS_PATH = DOCS / "data.js"
GEN_PATH = ROOT / "scripts" / "generate_synthetic_data.py"

sys.path.insert(0, str(ROOT / "scripts"))
import generate_synthetic_data as gen  # noqa: E402

EXPECTED_FILES = {
    ".gitignore",
    "README.md",
    "data/synthetic_ohlcv.csv",
    "docs/.nojekyll",
    "docs/THIRD-PARTY-NOTICES.md",
    "docs/app.js",
    "docs/data.js",
    "docs/index.html",
    "docs/notices.html",
    "docs/styles.css",
    "media/src/tslaiq-readme-hero.svg",
    "media/src/tslaiq-social-preview.svg",
    "media/tslaiq-readme-hero.png",
    "media/tslaiq-social-preview.png",
    "scripts/generate_synthetic_data.py",
    "tests/test_tutorial.py",
    "tests/verify_demo.py",
}

FORBIDDEN_PATTERNS = [
    ("local_user_path", re.compile(r"/Users/[A-Za-z0-9._-]+")),
    ("local_hostname", re.compile(r"\.local\b|Erturk-MacBook-Pro", re.I)),
    ("private_key_or_api_key", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----|AIza[0-9A-Za-z_-]{30,}|sk-[A-Za-z0-9_-]{24,}")),
    ("stale_private_repo_link", re.compile(r"github\.com/erturkeryavuz/TSLAIQ")),
    ("stale_private_pages_link", re.compile(r"erturkeryavuz\.github\.io/TSLAIQ")),
    ("external_font_or_cdn", re.compile(r"fonts\.googleapis\.com|fonts\.gstatic\.com|query1\.finance\.yahoo\.com")),
]


class TSLAIQDemoTests(unittest.TestCase):
    def test_exact_tracked_file_inventory(self):
        actual = {
            p.relative_to(ROOT).as_posix()
            for p in ROOT.rglob("*")
            if p.is_file() and ".git" not in p.parts and "__pycache__" not in p.parts and p.name != ".DS_Store"
        }
        self.assertEqual(actual, EXPECTED_FILES)

    def test_zero_forbidden_binary_or_legacy_artifacts(self):
        forbidden_exts = {".keras", ".h5", ".pkl", ".pt", ".ckpt", ".v2", ".ipynb", ".sqlite", ".sqlite3", ".db"}
        for p in ROOT.rglob("*"):
            if not p.is_file() or ".git" in p.parts:
                continue
            self.assertNotIn(p.suffix.lower(), forbidden_exts, f"Forbidden artifact: {p.relative_to(ROOT)}")
            self.assertNotIn("tsla_data", p.name.lower())
            self.assertNotIn("tfevents", p.name.lower())

    def test_synthetic_generator_byte_for_byte_reproducibility(self):
        raw1 = gen.generate_synthetic_ohlcv()
        raw2 = gen.generate_synthetic_ohlcv()
        self.assertEqual(raw1, raw2)
        enriched = gen.compute_indicators(raw1)
        payload = gen.build_payload(enriched)

        # Verify committed docs/data.js matches freshly generated bytes exactly
        header = (
            "/* Auto-generated deterministically by scripts/generate_synthetic_data.py "
            f"(seed={gen.SEED}, ticker={gen.TICKER}). 100% synthetic — zero real market data. */\n"
        )
        expected_js = header + "window.TSLAIQ_DATA = " + json.dumps(payload, separators=(",", ":")) + ";\n"
        actual_js = DATA_JS_PATH.read_text(encoding="utf-8")
        self.assertEqual(
            hashlib.sha256(actual_js.encode("utf-8")).hexdigest(),
            hashlib.sha256(expected_js.encode("utf-8")).hexdigest(),
            "docs/data.js is not byte-for-byte reproducible from scripts/generate_synthetic_data.py",
        )

    def test_ohlcv_and_date_invariants_on_all_1500_rows(self):
        with CSV_PATH.open("r", encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        self.assertEqual(len(rows), 1500)

        prev_date = None
        seen_dates = set()
        for idx, r in enumerate(rows):
            d_str = r["Date"]
            d = dt.date.fromisoformat(d_str)
            self.assertLess(d.weekday(), 5, f"Weekend date at row {idx}: {d_str}")
            self.assertNotIn(d_str, seen_dates, f"Duplicate date: {d_str}")
            seen_dates.add(d_str)
            if prev_date is not None:
                self.assertGreater(d, prev_date, f"Non-ascending date at row {idx}: {d_str}")
            prev_date = d

            o = float(r["Open"])
            h = float(r["High"])
            l = float(r["Low"])
            c = float(r["Close"])
            v = int(r["Volume"])
            for val in (o, h, l, c):
                self.assertTrue(math.isfinite(val), f"Non-finite price at row {idx}")
                self.assertGreater(val, 0.0, f"Non-positive price at row {idx}")
            self.assertGreaterEqual(h, max(o, c), f"High < max(O, C) at row {idx}")
            self.assertLessEqual(l, min(o, c), f"Low > min(O, C) at row {idx}")
            self.assertGreaterEqual(v, 0, f"Negative volume at row {idx}")

            # Post-warmup indicators must be finite (no NaN/Inf)
            if idx >= 49:
                for ind in ("RSI", "EMA20", "EMA50", "MACD", "MACD_Signal", "OBV"):
                    self.assertNotEqual(r[ind], "", f"Missing post-warmup {ind} at row {idx}")
                    val = float(r[ind])
                    self.assertTrue(math.isfinite(val), f"Non-finite {ind} at row {idx}")
                self.assertGreaterEqual(float(r["RSI"]), 0.0)
                self.assertLessEqual(float(r["RSI"]), 100.0)

    def test_zero_real_yahoo_finance_tsla_observations(self):
        csv_txt = CSV_PATH.read_text(encoding="utf-8")
        js_txt = DATA_JS_PATH.read_text(encoding="utf-8")
        # Known real TSLA Yahoo Finance sentinels from 2010-2025 must never appear
        for sentinel in ("2010-06-29", "281494500", "278743770", "479.86", "488.54", "284.700012"):
            self.assertNotIn(sentinel, csv_txt)
            self.assertNotIn(sentinel, js_txt)
        obj = json.loads(js_txt[js_txt.find("{") : js_txt.rfind("}") + 1])
        self.assertEqual(obj["meta"]["ticker"], "SYNTH-EQ")
        self.assertTrue(obj["meta"]["is_synthetic"])
        self.assertNotIn("training_runs", obj)
        self.assertNotIn("legacy_archives", obj)

    def test_zero_secrets_paths_stale_links_or_external_cdns(self):
        for p in ROOT.rglob("*"):
            if not p.is_file() or ".git" in p.parts or "__pycache__" in p.parts or p == Path(__file__).resolve():
                continue
            text = p.read_text(encoding="utf-8", errors="replace")
            for label, pat in FORBIDDEN_PATTERNS:
                self.assertIsNone(pat.search(text), f"Forbidden pattern '{label}' in {p.relative_to(ROOT)}")

    def test_synthetic_labeling_and_historical_separation(self):
        html = (DOCS / "index.html").read_text(encoding="utf-8")
        notices = (DOCS / "notices.html").read_text(encoding="utf-8")
        self.assertIn("SYNTH-EQ", html)
        self.assertIn("100% SYNTHETIC DATA", html)
        self.assertIn("https://github.com/erturkeryavuz/tslaiq-demo", html)
        self.assertIn("Archival Private Research Summary", html)
        self.assertIn("NOT TRAINED", html)
        self.assertIn("SYNTH-EQ", notices)
        self.assertNotRegex(html, r'<script[^>]+src="https?://')

    def test_js_syntax_valid(self):
        node = subprocess.run(["which", "node"], capture_output=True, text=True).stdout.strip()
        if not node:
            self.skipTest("node not installed")
        for js in ("data.js", "app.js"):
            r = subprocess.run([node, "--check", str(DOCS / js)], capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, f"JS syntax error in {js}: {r.stderr}")


if __name__ == "__main__":
    unittest.main(verbosity=2)
